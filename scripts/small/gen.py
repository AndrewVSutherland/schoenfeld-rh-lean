#!/usr/bin/env python3
"""Generator for SchoenfeldRH/Small/Data.lean (the checkpoint list of `SchoenfeldRH.Small.walk`).

usage:  python3 scripts/small/gen.py [N] > SchoenfeldRH/Small/Data.lean      (default N = 30000)

The interval [73, N] of integers is cut greedily into intervals [a, b] (the next one starts at b + 1) such
that the integer inequalities of `SchoenfeldRH.Small.checkIv` hold; `check` below is that function, verbatim,
in exact integer arithmetic, so the output is deterministic and nothing here has to be trusted: the Lean
kernel re-evaluates every inequality.  One entry per interval:

    (b, s, kp, ka, kb)   with   s = isqrt(a * 2^20),   kp = bitlength(a^64) - 1   (2^kp <= a^64),
                                ka = bitlength(L_a) - 1 (2^ka <= L_a),   kb = bitlength(L_b)   (L_b < 2^kb),

where L_n = lcm(1, ..., n), so that psi(n) = log L_n.
"""
import math, sys

N = int(sys.argv[1]) if len(sys.argv) > 1 else 30000
START = 73

L = [1] * (N + 2)
for n in range(1, N + 2):
    L[n] = L[n - 1] * (n // math.gcd(n, L[n - 1] % n))

LOG2_LO, LOG2_HI, TEN10 = 6931471803, 6931471808, 10 ** 10   # 0.6931471803 < log 2 < 0.6931471808
DEN = 2 ** 10 * 4096 * 10 ** 10 * 10 ** 10 * 8 * 31416       # denominators of F: 2^10, 64^2, (10^10)^2, 8 * 3.1416

def entry(a, b):
    return (b, math.isqrt(a * 2 ** 20), (a ** 64).bit_length() - 1, L[a].bit_length() - 1, L[b].bit_length())

def check(a, b, s, kp, ka, kb):
    fnum = s * kp * kp * LOG2_LO * LOG2_LO * 10000 * TEN10
    return (a <= b and s * s <= a * 2 ** 20 and 2 ** kp <= a ** 64 and 2 ** ka <= L[a] and L[b] < 2 ** kb
            and kb * LOG2_HI * DEN < fnum + a * TEN10 * DEN
            and (b + 1) * TEN10 * DEN < fnum + ka * LOG2_LO * DEN)

out, a = [], START
while a <= N:
    if not check(a, *entry(a, a)):
        sys.exit("no admissible interval starts at %d" % a)
    lo, hi = a, N                      # admissibility is monotone in b: bisect for the largest b
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if check(a, *entry(a, mid)):
            lo = mid
        else:
            hi = mid - 1
    out.append(entry(a, lo))
    a = lo + 1

# independent re-check of the whole list, as the Lean walk does it
a = START
for e in out:
    assert check(a, *e)
    a = e[0] + 1
assert a == N + 1

print("/-")
print("GENERATED by scripts/small/gen.py %d -- do not edit by hand." % N)
print("%d intervals [a, b] covering the integers %d..%d; entries (b, s, kp, ka, kb), see" % (len(out), START, N))
print("`SchoenfeldRH.Small.checkIv` in SchoenfeldRH/Small/Check.lean and the generator's docstring.")
print("-/")
print()
print("namespace SchoenfeldRH.Small")
print()
print("/-- Checkpoint data for `walk`: one entry `(b, s, kp, ka, kb)` per interval `[a, b]`. -/")
print("def data : List (Nat × Nat × Nat × Nat × Nat) := [")
lines = ["  (%d, %d, %d, %d, %d)" % e for e in out]
print(",\n".join(lines))
print("]")
print()
print("/-- One more than the last integer covered by `data`. -/")
print("def dataEnd : Nat := %d" % (N + 1))
print()
print("end SchoenfeldRH.Small")
